#!/usr/bin/env python3
"""Builds src/locales.ts (the translations the panel bundles) from locales/*.json.

Run it after editing a locale file:  python3 tools/build_locales.py
Each locales/<code>.json looks like {"language": "Name", "strings": {"English text": "Translation"}}.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for path in sorted(glob.glob(os.path.join(ROOT, "locales", "*.json"))):
    code = os.path.splitext(os.path.basename(path))[0]
    with open(path, "r", encoding="utf-8") as stream:
        out[code] = json.load(stream)["strings"]
body = json.dumps(out, ensure_ascii=True, indent=1, sort_keys=True)
with open(os.path.join(ROOT, "src", "locales.ts"), "w", encoding="utf-8") as stream:
    stream.write("// Generated by tools/build_locales.py from locales/*.json. Do not edit by hand.\n")
    stream.write("export const LOCALES: Record<string, Record<string, string>> = " + body + ";\n")
print("wrote src/locales.ts:", {k: len(v) for k, v in out.items()})
